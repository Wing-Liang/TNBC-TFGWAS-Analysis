# ==============================================================================
# 02_call_peaks_macs2.R
# Call scATAC-seq peaks with MACS2 (Signac CallPeaks), discovery cohort.
# Produces: peak set (Fig 2E, Table S1)
# Inputs  : data/GSE162798/scATAC/barcodes.tsv.gz
#           data/GSE162798/scATAC/peaks.bed.gz
#           data/GSE162798/scRNA/
# Outputs : results/singlecell/venn_diagram_sc_number.png
#           results/singlecell/peakcalling.bed
#           results/singlecell/peakcalling_df.bed
# Run     : Rscript scripts/01_singlecell_annotation/02_call_peaks_macs2.R   (from the repository root)
# ==============================================================================
# Analyzing chrom_assay scATAC-seq: 10x multiomic
# https://stuartlab.org/signac/articles/chrom_assay_vignette

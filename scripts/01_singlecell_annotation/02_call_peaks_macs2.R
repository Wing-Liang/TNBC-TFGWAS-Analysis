# server
setwd(TNBC_ROOT)

################################################################
###               (1) Pre-processing workflow                ###
################################################################
##  -----------------Load ATAc data -----------------
# start by creating a Seurat object using the peak/cell matrix and cell metadata
# generated by cellranger-atac, and store the path to the fragment file on disk in the Seurat object
counts <- Matrix::readMM("data/GSE162798/scATAC/matrix.mtx.gz")
barcodes <- readLines("data/GSE162798/scATAC/barcodes.tsv.gz")
peaks <- read.table("data/GSE162798/scATAC/peaks.bed.gz", sep="\t")
peaknames <- paste(peaks$V1, peaks$V2, peaks$V3, sep="-")

colnames(counts) <- barcodes
rownames(counts) <- peaknames

metadata <- read.csv(
  file = "GSM5484482_SNuBarARC-HBCA.scATAC.cell_metainfo.csv",
  header = TRUE,
  row.names = 1)

chrom_assay <- CreateChromatinAssay(
  counts = counts,
  sep = c(":", "-"),
  genome = 'hg19',
  fragments = "data/GSE162798/fragments/fragments.tsv.gz",
  min.cells = 1)
str(chrom_assay)
# create a seurat object
# Checking for 24373 cell barcodes

##  -----------------Load RNA data -----------------
rna_matrix <- Read10X('data/GSE162798/scRNA/')
dim(rna_matrix)
rna  <- CreateSeuratObject(counts = rna_matrix, project = 'RNA') #, min.cells = 5, min.features = 200)
# Warning: Feature names cannot have underscores ('_'), replacing with dashes ('-')
rna

# --------------- Doublet identification ---------------
# Load required libraries
suppressPackageStartupMessages({
  library(Seurat)
  library(SingleCellExperiment)
  library(scDblFinder)
})
# Convert Seurat object to SingleCellExperiment (SCE)
# Normalize the data
rna <- rna%>%NormalizeData()%>% ScaleData()
sce <- as.SingleCellExperiment(rna)

# Check available assays in the SCE object
assayNames(sce)

sce <- scDblFinder(sce)
# 5620 (20.7%) doublets called

# Extract results
table(colData(sce)$scDblFinder.class)
rna@meta.data$scDblFinder_class <- colData(sce)$scDblFinder.class
rna@meta.data$scDblFinder_score <- colData(sce)$scDblFinder.score

##  ----------------Find overlap barcodes between RNA and ATAC ----------------
dic0 = read.csv('GSM5484484_lib.coassay.std_cellname_dictionary.csv')
dic0$RNA = paste0(dic0$RNA_original_cell_name, '-1')
dic0$ATAC = paste0(dic0$ATAC_original_cell_name, '-1')
dic_ATAC = dic0[is.element(dic0$ATAC, colnames(chrom_assay)),]
dic_overlap = dic_ATAC[is.element(dic_ATAC$RNA, colnames(rna)),]

# Load library
library(VennDiagram)
rna_cells <- 27129
atac_cells <- 24373
overlap <- 22123

# Create the Venn diagram
venn_plot <- draw.pairwise.venn(
  area1 = rna_cells,          # Total RNA cells
  area2 = atac_cells,         # Total ATAC cells
  cross.area = overlap,       # Overlap between RNA and ATAC
  category = c("scRNA-seq", "scATAC-seq"), # Labels for the sets
  fill = c('#f9e79f', "#4DBBD5CC"),    # Colors for RNA and ATAC
  alpha = c(0.5, 0.5),        # Transparency for the circles
  lty = "blank",              # Line type for the circles
  cex = 1.9,                    # Font size for numbers
  cat.cex = 1.5 ,               # Font size for category labels
  cat.pos = c(-30, 30)       # Position of category labels
)

# Save the plot to a file (optional)
ggsave("results/singlecell/venn_diagram_sc_number.png", venn_plot, width = 7, height = 4)

# Display the plot
grid.draw(venn_plot)

##  -----------------Load ATAc data -----------------
length(barcodes) # [1] 24373
# Part 1: Barcodes ordered by colnames(atac_subset)
ordered_barcodes <- barcodes[match(colnames(atac_subset), barcodes)]
length(ordered_barcodes) # [1] 22123
all.equal(ordered_barcodes, colnames(atac_subset)) #[1] TRUE

# Verify the result
head(barcodes.ordered)
head(colnames(atac_subset))

# Part 2: Barcodes not in colnames(atac_subset)
unmatched_barcodes <- barcodes[!barcodes %in% colnames(atac_subset)]
length(unmatched_barcodes)#[1] 2250

# Append unmatched barcodes to the ordered ones
final_barcodes <- c(ordered_barcodes, unmatched_barcodes)
length(final_barcodes) # [1] 24373

colnames(counts) <- final_barcodes
rownames(counts) <- peaknames

metadata <- read.csv(
  file = "GSM5484482_SNuBarARC-HBCA.scATAC.cell_metainfo.csv",
  header = TRUE,
  row.names = 1)

chrom_assay <- CreateChromatinAssay(
  counts = counts,
  sep = c(":", "-"),
  genome = 'hg19',
  fragments = "data/GSE162798/fragments/fragments.tsv.gz",
  min.cells = 1)
str(chrom_assay)
# create a seurat object
# Checking for 24373 cell barcodes

atac <- CreateSeuratObject(
  counts = chrom_assay,
  assay = "ATAC",
  meta.data = metadata,
  project = 'SeuratProject'
)
atac

## ---------- Subsetting data to common barcodes and sorting----------
chrom_assay = subset(chrom_assay, cells=dic_overlap$ATAC)  #ChromatinAssay data with 142207 features for 22123 cells
atac_subset = subset(rna, cells=dic_overlap$RNA) #32738 features across 22123 samples within 1 assay

head(colnames(atac_subset))

# Replace RNA barcodes with corresponding ATAC barcodes
colnames(atac_subset) <- dic_overlap$ATAC[match(colnames(atac_subset), dic_overlap$RNA)]

head(colnames(atac_subset)) #showing the replaced ATAC cell names

# verify in the dic_overlap, showing the RNA cell names which have been replaced by ATAC cell names
dic_overlap$RNA[which(dic_overlap$ATAC %in% head(colnames(atac_subset)))]

# --------------- rename the rna cell name -----------------
# to check whether all
all.equal(colnames(atac_subset), colnames(chrom_assay))

atac_subset[['ATAC']]<-chrom_assay
atac_subset

# --------- Peak calling ---------------
DefaultAssay(atac_subset) <- 'ATAC'
atac_subset

#
#

peakcalling <- CallPeaks(
  object = atac_subset,
 macs2.path = Sys.which("macs2"),
 cleanup = FALSE)

df_peakcalling <- data.frame(seqnames=seqnames(peakcalling),
                 starts=start(peakcalling),
                 ends=end(peakcalling),
                 strands=strand(peakcalling),
                 name=c(paste("RNA_peak_", (1:length(peakcalling)))),
                 score=score(peakcalling),
                 fold_change=peakcalling$fold_change,
                 neg_log10pvalue_summit=peakcalling$neg_log10pvalue_summit,
                 neg_log10qvalue_summit=peakcalling$neg_log10qvalue_summit,
                 relative_summit_position=peakcalling$relative_summit_position)
head(df_peakcalling)

# save the peakcalling
setwd(TNBC_ROOT)
rtracklayer::export.bed(df_peakcalling,"results/singlecell/peakcalling.bed")

write.table(df_peakcalling,"results/singlecell/peakcalling_df.bed",row.names = F,sep = '\t',quote = F)
